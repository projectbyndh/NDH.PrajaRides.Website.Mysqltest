// Editable sections of the services list (/services) and the labels shared by every service page
// (/services/<name>). Each service's own text is in admin → Services. Starting content; the live
// content is in content_blocks. Service pages also fill {service}, {serviceLower}, {summary},
// {app} (the partner app, e.g. NepCab) and {count}.
export const fillService = (text: string, vars: Record<string, string | number>): string =>
  text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));

